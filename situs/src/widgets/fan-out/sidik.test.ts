// heksadesimal pertama. Satu nilai yang berubah, dihapus, ditambah, atau berpindah tempat membuat tes ini gagal dan menyebut
// jalurnya. Ini penguncian perubahan, bukan bukti kebenaran: kebenaran tiap nilai dijaga logika.test.ts, sumber.test.ts, dan
// teks.test.ts (turunan dari rekaman, kode lab, naskah, dan model), dan kalimat penting dikunci terbaca di kunci.test.ts. Setelah
// menyunting data dengan sengaja, cetak tabel baru dengan `SIDIK_CETAK=1 bun x vitest run src/widgets/fan-out/sidik.test.ts` dan
// tinjau tiap baris yang berubah. Putaran mutasi TANPA kunci baris tidak menyertakan berkas ini dan kunci.test.ts (analisis-kritis Prosedur E butir 12).
