const sidik = (s: string) => createHash("sha256").update(s).digest("hex").slice(0, 10);
const daun = (x: unknown, jalur: string): [string, string][] => {
  if (Array.isArray(x)) return x.flatMap((y, i) => daun(y, `${jalur}.${i}`));
  if (x && typeof x === "object") return Object.entries(x).flatMap(([k, v]) => daun(v, jalur ? `${jalur}.${k}` : k));
  return [[jalur, sidik(String(x))]];
};

