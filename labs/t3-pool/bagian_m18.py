"""Bagian m18 lab t3-pool (keputusan 957-959): M18 dengan beban nyata: pool 10, pool 50, client yang menyerah."""
from umum import *  # noqa: E402,F401,F403
from umum import b, d  # noqa: E402


def rekam_m18():
    bagian("A. Pool 10: push menggantung, client tanpa batas waktu, beban nyata 17,4 request per detik")
    be, pg = insiden(["-rentan", "push-dalam-tx"], 30.4,
                     tampil="$ ./api-t3 -rentan push-dalam-tx -lab   # pool 10, push timeout 0 (tanpa batas), idle-tx 0 (mati)",
                     titik=(1, 5, 9, 10))
    catat(f"# Pembayaran ke-10 tiba pada detik {kom(10 * PERIODE)} jadwal (10 ÷ 0,87). Cuplikan pg_stat_activity tiap 50 ms menandai saat koneksi ke-10 terlihat.")
    detik = penuh_antara(pg, 10, 10)
    catat(f"pool 10 penuh antara detik ke-{detik} dan ke-{detik + 1} sejak beban mulai (hitungan 10 ÷ 0,87 = {kom(10 * PERIODE)})")
    p = cetak_pool()
    harap((p["dipakai"], p["maks"], p["terbuka"]), (10, 10, 10), "pool penuh")
    be.tidur_sampai(30.4)
    be.henti()
    n1, n2 = len(be.nomor(1, 199, "baca")), len(be.nomor(201, 400, "baca"))
    r1, r2 = be.rekap(1, 199, "baca"), be.rekap(201, 400, "baca")
    harap(r1, {200: n1}, "pembacaan sebelum pool penuh")
    harap(r2, {0: n2}, "pembacaan sesudah pool penuh")
    catat(f"# Pembacaan sebelum pool penuh (request 1 sampai 199): {n1} pembacaan: {ringkas(r1)}")
    catat(f"# Pembacaan sesudah pool penuh (request 201 sampai 400): {n2} pembacaan: {ringkas(r2)}")
    n_bayar = bayar_terjadwal(30.4)
    belum, gantung = be.dalam_proses(), menggantung()
    harap((n_bayar, belum, gantung), (26, 26, 10), "keadaan sesudah 30 detik")
    catat(f"# Sesudah 30 detik: {n_bayar} pembayaran dikirim, {belum} belum dijawab. Di layanan push {gantung} permintaan menggantung, jadi {belum - gantung} pembayaran menunggu koneksi di API.")
    catat(f"# Hitungan untuk t = 30 detik: L = 0,87 × (0,02 + 30) = {kom(LAMBDA * (W_DB + 30))} koneksi yang dibutuhkan. Diukur: {belum} pembayaran dalam proses, tetapi tidak ada yang selesai, "
          f"jadi angka itu hanya jadwal × waktu (0,87 × 30,4 = {kom(LAMBDA * 30.4)}), bukan ujian L = λ × W (ujiannya di little.txt). Pool hanya muat 10; sisanya mengantre.")
    pg.henti()
    hentikan(PORT, PORT_PUSH)

    bagian("B. Pool 50 (usul Raka): pool lebih besar hanya menunda")
    be, pg = insiden(["-rentan", "push-dalam-tx", "-pool", "50"], 61.6,
                     tampil="$ ./api-t3 -rentan push-dalam-tx -pool 50 -lab   # pool 50, push timeout 0, idle-tx 0",
                     titik=(1, 25, 49, 50))
    catat(f"# Pembayaran ke-50 tiba pada detik {kom(50 * PERIODE)} jadwal (50 ÷ 0,87).")
    detik = penuh_antara(pg, 50, 50)
    catat(f"pool 50 penuh antara detik ke-{detik} dan ke-{detik + 1} sejak beban mulai (hitungan 50 ÷ 0,87 = {kom(50 * PERIODE)})")
    p = cetak_pool()
    harap((p["dipakai"], p["maks"], p["terbuka"]), (50, 50, 50), "pool 50 penuh")
    be.tidur_sampai(61.6)
    be.henti()
    n1, n2 = len(be.nomor(1, 999, "baca")), len(be.nomor(1001, 1018, "baca"))
    r1, r2 = be.rekap(1, 999, "baca"), be.rekap(1001, 1018, "baca")
    harap(r1, {200: n1}, "pembacaan sebelum pool 50 penuh")
    harap(r2, {0: n2}, "pembacaan sesudah pool 50 penuh")
    catat(f"# Sebelum pool penuh tidak ada request yang gagal. Pembacaan request 1 sampai 999: {n1} pembacaan: {ringkas(r1)}")
    catat(f"# Sesudah pool penuh (request 1001 sampai 1018): {n2} pembacaan: {ringkas(r2)}")
    n_bayar = bayar_terjadwal(61.6)
    belum, gantung = be.dalam_proses(), menggantung()
    harap((n_bayar, belum, gantung), (53, 53, 50), "keadaan sesudah 61,6 detik")
    catat(f"# Sesudah 61,6 detik: {n_bayar} pembayaran dikirim, {belum} belum dijawab, {gantung} menggantung di layanan push, {belum - gantung} menunggu koneksi.")
    catat("# Pool 50 menunda pembekuan dari 11,5 ke 57,5 detik. Penyebabnya, layanan push tanpa batas waktu di dalam transaction, tidak berubah.")
    pg.henti()
    hentikan(PORT, PORT_PUSH)

    bagian("C. Client menyerah sesudah 5 detik: koneksi kembali dan pool tidak penuh")
    be, pg = insiden(["-rentan", "push-dalam-tx"], 30.4, durasi_bayar_klien=5.0,
                     tampil="$ ./api-t3 -rentan push-dalam-tx -lab   # sama seperti A")
    be.tidur_sampai(30.4)
    be.henti()
    puncak = pg.puncak(1)
    harap(puncak, 5, "puncak koneksi idle in transaction dengan client yang menyerah")
    catat(f"koneksi idle in transaction: puncak {puncak} dari 10 (0,87 × 5 detik = {kom(LAMBDA * 5, 2)}, jadi paling banyak 5)")
    rb, rr = be.rekap(1, 400, "bayar"), be.rekap(1, 400, "baca")
    nb, nr = len(be.nomor(1, 400, "bayar")), len(be.nomor(1, 400, "baca"))
    harap(rb, {0: nb}, "pembayaran yang menyerah")
    harap(rr, {200: nr}, "pembacaan saat client pembayaran menyerah")
    catat(f"pembayaran request 1 sampai 400: {nb} pembayaran: {ringkas(rb)}")
    catat(f"pembacaan request 1 sampai 400: {nr} pembacaan: {ringkas(rr)}")
    sql("SELECT count(*) AS jurnal_bayar FROM jurnal WHERE jenis = 'bayar'")
    harap(satu("SELECT count(*) FROM jurnal WHERE jenis = 'bayar'"), 0, "tidak ada jurnal bayar")
    gantung = menggantung()
    harap(gantung, bayar_terjadwal(30.4), "handler tetap menunggu push")
    catat(f"# Sesudah 30 detik layanan push masih menahan {gantung} permintaan: handler tidak berhenti walau client pergi (push memakai konteks yang dilepas dari request).")
    catat("# Transaction pembayaran dibatalkan saat konteks request batal, jadi koneksi kembali ke pool dan tidak ada jurnal. Pool 10 baru penuh bila client menunggu lebih dari 10 ÷ 0,87 = 11,5 detik.")
    pg.henti()
    hentikan(PORT, PORT_PUSH)
    tulis("m18.txt", "M18: layanan push menggantung dan pool 10 koneksi", lab="t3-pool", keputusan="957")
